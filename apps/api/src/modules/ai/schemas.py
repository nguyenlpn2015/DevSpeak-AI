"""Pydantic schemas for AI evaluation and feedback generation."""

from pydantic import BaseModel, Field, field_validator


class EvaluationRequest(BaseModel):
    """User answer submission request for a specific interview question."""

    question_id: str = Field(
        min_length=1,
        max_length=100,
        description="Unique identifier of the question being answered",
    )
    session_id: str | None = Field(
        default=None,
        max_length=36,
        description="Optional session ID to persist evaluation history against",
    )
    user_answer: str = Field(
        min_length=10,
        max_length=4000,
        description="The candidate's spoken or written English answer (10 - 4000 characters)",
    )

    @field_validator("user_answer")
    @classmethod
    def validate_user_answer(cls, value: str) -> str:
        """Validate answer length after stripping leading/trailing whitespace."""
        stripped = value.strip()
        if len(stripped) < 10:
            raise ValueError("user_answer must contain at least 10 non-whitespace characters")
        if len(value) > 4000:
            raise ValueError("user_answer cannot exceed 4000 characters")
        return value


class ScoreBreakdown(BaseModel):
    """Granular scores evaluating English and technical competency (1 - 10 scale)."""

    grammar_score: int = Field(
        ge=1, le=10, description="English grammar, tense consistency, and syntax"
    )
    technical_score: int = Field(
        ge=1,
        le=10,
        description="Technical accuracy and relevant terminology coverage",
    )
    clarity_score: int = Field(
        ge=1,
        le=10,
        description="Structure, conciseness, and clarity (STAR framework where applicable)",
    )
    overall_score: float = Field(ge=1.0, le=10.0, description="Weighted composite score")


class FeedbackSection(BaseModel):
    """Categorized feedback points for targeted candidate improvement."""

    grammar_feedback: list[str] = Field(
        default_factory=list,
        description="Observations on grammar, vocabulary diversity, and sentence structure",
    )
    technical_feedback: list[str] = Field(
        default_factory=list,
        description="Analysis of technical concepts covered versus missing critical points",
    )
    clarity_structure_feedback: list[str] = Field(
        default_factory=list,
        description="Advice on professional articulation, conciseness, and narrative structure",
    )


class FeedbackReport(BaseModel):
    """Complete evaluation report returned to the candidate."""

    question_id: str
    scores: ScoreBreakdown
    feedback: FeedbackSection
    model_answer: str = Field(
        description="Ideal benchmark answer for self-study and pronunciation practice"
    )
    suggested_followups: list[str] = Field(
        default_factory=list,
        description="Probe questions an interviewer would typically ask next",
    )
    disclaimer: str = Field(
        default=(
            "This evaluation is generated by DevSpeak AI's deterministic heuristic mock provider "
            "for practice purposes only. It is heuristic feedback, not an objectively validated "
            "standardized measurement of English proficiency, nor is it generated by a live commercial language model."
        ),
        description="Transparency statement declaring heuristic mock nature of evaluation",
    )
