"""SQLAlchemy ORM models for interview sessions and attempts."""

import uuid
from datetime import datetime
from typing import Any

from sqlalchemy import JSON, DateTime, Float, ForeignKey, Integer, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from src.db.base import Base, utc_now
from src.modules.auth.models import User


class InterviewSession(Base):
    """Represents a continuous candidate practice session for a specific question."""

    __tablename__ = "interview_sessions"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
        index=True,
    )
    user_id: Mapped[str | None] = mapped_column(
        String(36),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
        doc="Optional reference to registered candidate account",
    )
    question_id: Mapped[str] = mapped_column(
        String(100),
        nullable=False,
        index=True,
        doc="Logical reference to question in the version-controlled question catalog",
    )
    status: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
        default="in_progress",
        index=True,
        doc="Session lifecycle status ('in_progress', 'completed', 'abandoned')",
    )
    session_metadata: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        default=dict,
        doc="Arbitrary, non-secret session context (e.g. client role, focus area)",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        index=True,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        onupdate=utc_now,
    )

    # Relationships
    user: Mapped["User | None"] = relationship(  # noqa: F821
        "User",
        back_populates="sessions",
    )
    attempts: Mapped[list["InterviewAttempt"]] = relationship(
        "InterviewAttempt",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="InterviewAttempt.created_at.asc()",
    )
    messages: Mapped[list["InterviewMessage"]] = relationship(
        "InterviewMessage",
        back_populates="session",
        cascade="all, delete-orphan",
        order_by="InterviewMessage.turn_index.asc()",
    )

    def __repr__(self) -> str:
        return (
            f"<InterviewSession id={self.id} question_id={self.question_id} status={self.status}>"
        )


class InterviewAttempt(Base):
    """Represents a single evaluation attempt within an interview session."""

    __tablename__ = "interview_attempts"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
        index=True,
    )
    session_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    user_answer: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Candidate raw answer text submitted for evaluation",
    )
    feedback_snapshot: Mapped[dict[str, Any]] = mapped_column(
        JSON,
        nullable=False,
        doc="Immutable snapshot of FeedbackReport generated by AIProvider at evaluation time",
    )
    overall_score: Mapped[float | None] = mapped_column(
        Float,
        nullable=True,
        index=True,
        doc="Indexed overall score (1.0 - 10.0) extracted from feedback snapshot",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        index=True,
    )

    # Relationships
    session: Mapped["InterviewSession"] = relationship(
        "InterviewSession",
        back_populates="attempts",
    )

    def __repr__(self) -> str:
        return f"<InterviewAttempt id={self.id} session_id={self.session_id} score={self.overall_score}>"


class InterviewMessage(Base):
    """Represents a conversational turn in a multi-turn interview dialogue."""

    __tablename__ = "interview_messages"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=lambda: str(uuid.uuid4()),
        index=True,
    )
    session_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("interview_sessions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    role: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        index=True,
        doc="Speaker role: 'interviewer' or 'candidate'",
    )
    content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        doc="Dialogue message text",
    )
    turn_index: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
        index=True,
        doc="Sequential message sequence order within the interview session",
    )
    feedback_snapshot: Mapped[dict[str, Any] | None] = mapped_column(
        JSON,
        nullable=True,
        default=None,
        doc="Optional structured evaluation report attached when concluding an interview",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utc_now,
        index=True,
    )

    # Relationships
    session: Mapped["InterviewSession"] = relationship(
        "InterviewSession",
        back_populates="messages",
    )

    def __repr__(self) -> str:
        return f"<InterviewMessage id={self.id} session_id={self.session_id} role={self.role} turn={self.turn_index}>"
